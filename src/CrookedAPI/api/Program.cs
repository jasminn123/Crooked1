using Microsoft.Extensions.FileProviders;
using Npgsql;
using Crooked;
using Crooked.Models;
using Crooked.Services;

var builder = WebApplication.CreateBuilder(args);

// Railway assigns the listening port at runtime through PORT.
var port = Environment.GetEnvironmentVariable("PORT");
if (!string.IsNullOrEmpty(port))
{
    builder.WebHost.UseUrls($"http://0.0.0.0:{port}");
}

builder.Services.AddControllers();
builder.Services.AddEndpointsApiExplorer();

// Register threshold forecast options and service
builder.Services.Configure<ThresholdForecastOptions>(builder.Configuration.GetSection("ThresholdForecast"));
builder.Services.AddHostedService<ThresholdForecastService>();

builder.Services.AddCors(options =>
{
    options.AddPolicy("AllowAll", policy =>
    {
        policy.AllowAnyOrigin()
              .AllowAnyMethod()
              .AllowAnyHeader();
    });
});

var app = builder.Build();

EnsureDatabaseSetup();

var frontend = Path.Combine(app.Environment.ContentRootPath, "Frontend");
var pages = new PhysicalFileProvider(Path.Combine(frontend, "page"));
var uploads = Path.Combine(app.Environment.ContentRootPath, "wwwroot");
Directory.CreateDirectory(uploads);

app.UseDefaultFiles(new DefaultFilesOptions { FileProvider = pages });
app.UseStaticFiles(new StaticFileOptions { FileProvider = pages });
// Pages link to ../page, ../design, ../javascript and ../assets, so Frontend is also served from the root.
app.UseStaticFiles(new StaticFileOptions { FileProvider = new PhysicalFileProvider(frontend) });
app.UseStaticFiles(new StaticFileOptions { FileProvider = new PhysicalFileProvider(uploads) });

app.MapControllers();
app.Run();

void EnsureDatabaseSetup()
{
    using var connection = new NpgsqlConnection(DatabaseConfig.ConnectionString);
    connection.Open();

    using var command = new NpgsqlCommand(
        @"ALTER TABLE products
              ADD COLUMN IF NOT EXISTS is_active BOOLEAN NOT NULL DEFAULT TRUE,
              ADD COLUMN IF NOT EXISTS low_stock_threshold INTEGER NOT NULL DEFAULT 5,
              ADD COLUMN IF NOT EXISTS sales_velocity_rating TEXT NOT NULL DEFAULT 'slow',
              ADD COLUMN IF NOT EXISTS last_threshold_update TIMESTAMPTZ;
          CREATE TABLE IF NOT EXISTS product_daily_sales (
              product_id INTEGER NOT NULL,
              sale_date DATE NOT NULL,
              quantity_sold INTEGER NOT NULL DEFAULT 0 CHECK (quantity_sold >= 0),
              PRIMARY KEY (product_id, sale_date)
          );
          CREATE TABLE IF NOT EXISTS forecast_notifications (
              id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
              product_id INTEGER NOT NULL,
              product_name TEXT NOT NULL,
              image_url TEXT,
              old_threshold INTEGER NOT NULL,
              new_threshold INTEGER NOT NULL,
              old_velocity TEXT NOT NULL,
              new_velocity TEXT NOT NULL,
              created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
              is_read BOOLEAN NOT NULL DEFAULT FALSE
          );
          CREATE INDEX IF NOT EXISTS idx_forecast_notifications_unread
              ON forecast_notifications (is_read, created_at DESC);
          CREATE TABLE IF NOT EXISTS transaction_items (
              transaction_item_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
              transaction_id INTEGER NOT NULL REFERENCES transactions(transaction_id) ON DELETE CASCADE,
              product_id INTEGER NOT NULL REFERENCES products(id),
              product_name TEXT NOT NULL,
              category TEXT NOT NULL DEFAULT '',
              size TEXT NOT NULL DEFAULT '',
              color TEXT NOT NULL DEFAULT '',
              quantity INTEGER NOT NULL CHECK (quantity > 0),
              unit_price NUMERIC(12, 2) NOT NULL CHECK (unit_price >= 0),
              exchange_reason TEXT NOT NULL DEFAULT ''
          );
          ALTER TABLE transaction_items
              ADD COLUMN IF NOT EXISTS exchange_reason TEXT NOT NULL DEFAULT '';
          CREATE INDEX IF NOT EXISTS idx_transaction_items_transaction
              ON transaction_items (transaction_id);
          ALTER TABLE transactions
              ADD COLUMN IF NOT EXISTS assisted_by TEXT NOT NULL DEFAULT 'Unknown',
              ADD COLUMN IF NOT EXISTS has_exchange BOOLEAN NOT NULL DEFAULT FALSE;
          UPDATE transactions
          SET has_exchange = TRUE
          WHERE EXISTS (
              SELECT 1
              FROM transaction_items
              WHERE transaction_items.transaction_id = transactions.transaction_id
                AND transaction_items.exchange_reason <> ''
          );",
        connection);
    command.ExecuteNonQuery();
}