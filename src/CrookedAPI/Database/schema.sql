-- Schema updates the app applies at startup (DatabaseSetup.EnsureSchema).
-- Every statement is idempotent, so this is safe to run on each start and against a database
-- that is already up to date. It can also be run by hand in the Supabase SQL editor.

ALTER TABLE products
    ADD COLUMN IF NOT EXISTS is_active BOOLEAN NOT NULL DEFAULT TRUE,
    ADD COLUMN IF NOT EXISTS low_stock_threshold INTEGER NOT NULL DEFAULT 5,
    ADD COLUMN IF NOT EXISTS sales_velocity_rating TEXT NOT NULL DEFAULT 'slow',
    ADD COLUMN IF NOT EXISTS last_threshold_update TIMESTAMPTZ;

CREATE TABLE IF NOT EXISTS product_daily_sales (
    product_id INTEGER NOT NULL,
    sale_date DATE NOT NULL,
    quantity_sold INTEGER NOT NULL DEFAULT 0 CHECK (quantity_sold >= 0),
    PRIMARY KEY (product_id, sale_date)
);

CREATE TABLE IF NOT EXISTS forecast_notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id INTEGER NOT NULL,
    product_name TEXT NOT NULL,
    image_url TEXT,
    old_threshold INTEGER NOT NULL,
    new_threshold INTEGER NOT NULL,
    old_velocity TEXT NOT NULL,
    new_velocity TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    is_read BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE INDEX IF NOT EXISTS idx_forecast_notifications_unread
    ON forecast_notifications (is_read, created_at DESC);

-- The latest sales forecast for each product (one row per size and color), written by
-- ThresholdForecastService. method is 'ml' (the ML.NET model) or 'average' (the 7-day average),
-- and reason says why the average was used. model_error and average_error are each method's
-- average miss in units per week when both were backtested on the last backtest_weeks weeks.
CREATE TABLE IF NOT EXISTS product_forecasts (
    product_id INTEGER PRIMARY KEY REFERENCES products(id) ON DELETE CASCADE,
    method TEXT NOT NULL,
    reason TEXT NOT NULL DEFAULT '',
    predicted_units NUMERIC(10, 2) NOT NULL,
    predicted_low NUMERIC(10, 2) NOT NULL,
    predicted_high NUMERIC(10, 2) NOT NULL,
    horizon_days INTEGER NOT NULL,
    trend TEXT NOT NULL DEFAULT '',
    history_days INTEGER NOT NULL DEFAULT 0,
    model_error NUMERIC(10, 2),
    average_error NUMERIC(10, 2),
    backtest_weeks INTEGER NOT NULL DEFAULT 0,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS transaction_items (
    transaction_item_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transaction_id INTEGER NOT NULL REFERENCES transactions(transaction_id) ON DELETE CASCADE,
    product_id INTEGER NOT NULL REFERENCES products(id),
    product_name TEXT NOT NULL,
    category TEXT NOT NULL DEFAULT '',
    size TEXT NOT NULL DEFAULT '',
    color TEXT NOT NULL DEFAULT '',
    quantity INTEGER NOT NULL CHECK (quantity > 0),
    unit_price NUMERIC(12, 2) NOT NULL CHECK (unit_price >= 0),
    exchange_reason TEXT NOT NULL DEFAULT ''
);
ALTER TABLE transaction_items
    ADD COLUMN IF NOT EXISTS exchange_reason TEXT NOT NULL DEFAULT '';
CREATE INDEX IF NOT EXISTS idx_transaction_items_transaction
    ON transaction_items (transaction_id);

ALTER TABLE transactions
    ADD COLUMN IF NOT EXISTS assisted_by TEXT NOT NULL DEFAULT 'Unknown',
    ADD COLUMN IF NOT EXISTS has_exchange BOOLEAN NOT NULL DEFAULT FALSE,
    ADD COLUMN IF NOT EXISTS payment_method TEXT;
UPDATE transactions
SET has_exchange = TRUE
WHERE NOT has_exchange
  AND EXISTS (
      SELECT 1
      FROM transaction_items
      WHERE transaction_items.transaction_id = transactions.transaction_id
        AND transaction_items.exchange_reason <> ''
  );
-- Sales saved before payment methods were stored: the POS gives cash sales a generated
-- REF-... reference and GCash sales the customer's GCash reference number.
UPDATE transactions
SET payment_method = CASE
        WHEN reference_id LIKE 'REF-%' THEN 'Cash'
        WHEN COALESCE(reference_id, '') <> '' THEN 'GCash'
        ELSE 'Unknown'
    END
WHERE payment_method IS NULL;
CREATE INDEX IF NOT EXISTS idx_transactions_date_time
    ON transactions (date_time DESC);

CREATE TABLE IF NOT EXISTS exchanges (
    exchange_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transaction_id INTEGER NOT NULL REFERENCES transactions(transaction_id) ON DELETE CASCADE,
    processed_by TEXT NOT NULL DEFAULT 'Unknown',
    notes TEXT NOT NULL DEFAULT '',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_exchanges_transaction
    ON exchanges (transaction_id);

CREATE TABLE IF NOT EXISTS exchange_items (
    exchange_item_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    exchange_id BIGINT NOT NULL REFERENCES exchanges(exchange_id) ON DELETE CASCADE,
    returned_product_id INTEGER NOT NULL REFERENCES products(id),
    returned_product_name TEXT NOT NULL,
    returned_size TEXT NOT NULL DEFAULT '',
    returned_color TEXT NOT NULL DEFAULT '',
    new_product_id INTEGER NOT NULL REFERENCES products(id),
    new_size TEXT NOT NULL DEFAULT '',
    new_color TEXT NOT NULL DEFAULT '',
    quantity INTEGER NOT NULL CHECK (quantity > 0),
    unit_price NUMERIC(12, 2) NOT NULL CHECK (unit_price >= 0),
    reason TEXT NOT NULL DEFAULT ''
);
CREATE INDEX IF NOT EXISTS idx_exchange_items_exchange
    ON exchange_items (exchange_id);

-- Discount coupons. The owner creates them on the Discounts page and cashiers type the code at
-- the POS. discount_type is 'percent' (value is a whole-number percentage) or 'fixed' (value is
-- pesos off the subtotal). Blank dates mean no start or end date and a blank max_uses means no
-- usage limit. Codes are unique ignoring case.
CREATE TABLE IF NOT EXISTS discounts (
    discount_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code TEXT NOT NULL,
    description TEXT NOT NULL DEFAULT '',
    discount_type TEXT NOT NULL CHECK (discount_type IN ('percent', 'fixed')),
    value NUMERIC(12, 2) NOT NULL CHECK (value > 0 AND (discount_type = 'fixed' OR value <= 100)),
    min_purchase NUMERIC(12, 2) NOT NULL DEFAULT 0 CHECK (min_purchase >= 0),
    max_uses INTEGER CHECK (max_uses IS NULL OR max_uses > 0),
    times_used INTEGER NOT NULL DEFAULT 0 CHECK (times_used >= 0),
    starts_on DATE,
    ends_on DATE,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_by TEXT NOT NULL DEFAULT 'Unknown',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE UNIQUE INDEX IF NOT EXISTS idx_discounts_code
    ON discounts (upper(code));

-- The coupon a sale used. total_amount is what the customer paid, after discount_amount.
ALTER TABLE transactions
    ADD COLUMN IF NOT EXISTS discount_code TEXT,
    ADD COLUMN IF NOT EXISTS discount_amount NUMERIC(12, 2) NOT NULL DEFAULT 0;

-- Manual discounts: instead of a coupon, the cashier types a whole-number percentage. Owners can
-- give up to 100%; staff up to staff_max_percent, which the owner sets on the Discounts page
-- (0 turns them off for staff). discount_settings always has exactly one row.
CREATE TABLE IF NOT EXISTS discount_settings (
    id INTEGER PRIMARY KEY DEFAULT 1 CHECK (id = 1),
    staff_max_percent INTEGER NOT NULL DEFAULT 10 CHECK (staff_max_percent BETWEEN 0 AND 100),
    updated_by TEXT NOT NULL DEFAULT 'System',
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
INSERT INTO discount_settings (id) VALUES (1) ON CONFLICT (id) DO NOTHING;

-- A sale with a manual discount keeps discount_code NULL; discount_amount is what came off.
ALTER TABLE transactions
    ADD COLUMN IF NOT EXISTS manual_discount_percent INTEGER
        CHECK (manual_discount_percent IS NULL OR manual_discount_percent BETWEEN 1 AND 100);

-- The kind of each activity log entry (ActivityTypes in api/Models/Activity.cs), for the Activity
-- Logs page's filter. Entries written before the column existed are sorted by their wording, once.
ALTER TABLE activity_logs
    ADD COLUMN IF NOT EXISTS activity_type TEXT NOT NULL DEFAULT '';
UPDATE activity_logs
SET activity_type = CASE
        WHEN action IN ('Logged into the system', 'Logged out of the system') THEN 'Login'
        WHEN action LIKE 'Processed sale%' THEN 'Sale'
        WHEN action LIKE 'Exchanged %' THEN 'Exchange'
        WHEN action LIKE '%from Excel' THEN 'Import'
        WHEN action LIKE '%discount coupon:%' THEN 'Discount'
        WHEN action LIKE '%product:%' THEN 'Product'
        WHEN action = 'Changed their password'
          OR action LIKE 'Archived:%' OR action LIKE 'Unarchived:%'
          OR action LIKE 'Changed password:%' OR action LIKE 'Changed role:%'
          OR action LIKE 'Created staff account:%' OR action LIKE 'Reset the owner password%' THEN 'Account'
        ELSE 'Other'
    END
WHERE activity_type = '';
CREATE INDEX IF NOT EXISTS idx_activity_logs_date
    ON activity_logs (date_occurred DESC);

-- Row level security. Pages receive the public Supabase anon key for live updates, and without
-- RLS that key could read and change every table (users included) through Supabase's REST API.
-- With RLS on and no policies, the anon key gets nothing. The app connects as the table owner,
-- which RLS does not apply to, so the app itself is unaffected.
DO $$
DECLARE
    shop_table RECORD;
BEGIN
    FOR shop_table IN
        SELECT tablename
        FROM pg_tables
        WHERE schemaname = 'public' AND tableowner = current_user AND NOT rowsecurity
    LOOP
        EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY', shop_table.tablename);
    END LOOP;
END $$;
